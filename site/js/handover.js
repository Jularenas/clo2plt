// Operator spec sheet. Mirrors handover.py, built from converted markers
// rather than by re-reading the .plt files.

import * as classify from "./classify.js";

const isAlternate = (name) => /rotat|alternate/i.test(name);

export function specSheet(files) {
  let cal = "";
  let test = "";
  let hasAlternates = false;
  const lines = [];

  for (const f of files) {
    const [minx, miny, maxx, maxy] = f.extent;
    const w = maxx - minx;
    const h = maxy - miny;
    if (/calib/i.test(f.name)) cal = f.name;
    else if (/test/i.test(f.name)) test = f.name;

    const stats =
      `      ${f.polylines} polylines, ${f.points.toLocaleString("en-US")} points, ` +
      `${f.labels} label${f.labels === 1 ? "" : "s"}\n`;

    if (isAlternate(f.name)) {
      hasAlternates = true;
      lines.push(
        `  ${f.name}\n` +
          `      [ALTERNATE] the same marker turned 90 degrees.\n` +
          `      Use ONLY if the standard file above prints turned the\n` +
          `      wrong way. The finished marker is the same size either\n` +
          `      way: ${Math.min(w, h).toFixed(0)} mm across by ${Math.max(w, h).toFixed(0)} mm long.\n` +
          stats
      );
    } else {
      lines.push(
        `  ${f.name}\n` +
          `      plots ${w.toFixed(1)} x ${h.toFixed(1)} mm   -- needs paper >= ${(w + 40).toFixed(0)} mm wide\n` +
          stats
      );
    }
  }

  const pens = classify.ORDER.filter((k) => k !== classify.UNKNOWN)
    .map((k) => `  Pen ${classify.DEFAULT_PENS[k]}   ${k}\n`)
    .join("");

  const orient = hasAlternates
    ? "\nBoth orientations are supplied, so please do NOT rotate anything in\n" +
      "your software -- use the file that fits. A RIP that rotates sometimes\n" +
      "rescales as well, which would silently change the pattern size.\n"
    : "\nIf a file plots turned the wrong way, please say so rather than\n" +
      "rotating it in your software -- a RIP that rotates sometimes rescales\n" +
      "as well. A pre-rotated file can be supplied instead.\n";

  return `PLOTTER FILE SPECIFICATION
==========================

Format        HP-GL (plain, not HP-GL/2). Plain ASCII text.
Units         40 plotter units per millimetre (1016 per inch, 0.025 mm).
              This is the HP-GL default resolution.
Coordinates   Absolute (PA). Origin bottom-left. No scaling applied.
Scale         1:1. These are true garment pattern dimensions -- please do
              not fit-to-page, auto-scale, or rotate to fit.
Instructions  IN, PA, SP, PU, PD, LB, SI, DI, DT only. No HP-GL/2
              extensions (no PE, PW, TR), no arcs, no raster.

FILES
Each line shows the size the file plots at, and the minimum paper width it
needs. Files marked ALTERNATE are the same job turned 90 degrees -- print
one or the other, never both.

${lines.join("")}
PEN ASSIGNMENT
Each pen carries one kind of pattern line. On a single-ink plotter they
will all print the same colour, which is expected -- the separation is so
that individual line types can be suppressed if you need that.

${pens}
ORIENTATION -- PLEASE READ
The HP-GL X axis must map ACROSS the paper width, and Y along the feed.
Each file's paper requirement is listed above; nothing here needs to be
rotated or scaled to fit.
${orient}
CHECK BEFORE PRINTING THE LARGE FILES
  * Please run "${cal || "the calibration file"}" first. It contains a 200 mm square.
    If it does not measure exactly 200 mm, something in the chain is
    rescaling, and every marker will be wrong by that same factor.
  * "${test || "the single-piece test file"}" is a single small pattern piece.
    Worth running second to confirm orientation before committing a full
    marker.

Generated by clo2plt from CLO 3D PDF exports.
`;
}
